"""Generate docs/FORGEAI.brief - the presentation deck - from committed artifacts.

Every number on a slide is read from a file in this repository at generation time
(demo runs, the human-baseline comparison, the benchmark results, the model
selection table, the test-suite). Re-run after any new run:

    python scripts/make_brief.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HR = ROOT / "demos" / "hr-shore-staff" / "run"
PR = ROOT / "demos" / "ship-spares-procurement" / "run"


def j(p: Path, default=None):
    try:
        if p.suffix == ".jsonl":
            return [json.loads(x) for x in p.read_text(encoding="utf-8").splitlines() if x.strip()]
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return default


def frac(r):
    return f"{r['passed']}/{r['n']}" if r and r.get("n") else "n/a"


def pct(x):
    return "n/a" if x is None else f"{round(100 * x)}%"


def ci(r):
    return f"{round(100 * r['ci95'][0])}-{round(100 * r['ci95'][1])}%" if r and r.get("n") else ""


def run_facts(d: Path) -> dict:
    rep, g, ev = j(d / "report.json", {}), j(d / "03_groundability.json", {}), j(d / "05_evalset.json", {})
    tools, its, ch, can = j(d / "04_tool_decisions.json", []), j(d / "07_iterations.json", []), j(d / "07_changes.jsonl", []), j(d / "08_judge_canaries.json", {})
    req = j(d / "02_requirements.json", {})
    verdicts = j(d / "09_final_verdicts.jsonl", [])
    meth = [f["method"] for v in verdicts for f in v.get("facts", [])]
    st = ev.get("stats", {})
    return {
        "rep": rep, "g": g, "st": st, "tools": tools, "its": its, "changes": ch, "can": can, "req": req,
        "dropped": sum(v for k, v in st.get("checks", {}).items() if k.startswith("dropped")),
        "leak": st.get("checks", {}).get("dropped_parametric_leakage", 0),
        "code_share": (sum(1 for m in meth if m.startswith("deterministic")) / len(meth)) if meth else None,
        "attached": [t["tool"] for t in tools if t["attach"]],
        "vetoed": [t for t in tools if t["model_said"] and not t["attach"]],
        "minutes": round((j(d / "manifest.json", {}).get("meter") or {}).get("wall_seconds", 0) / 60, 1),
    }


def main() -> int:
    hr, pr = run_facts(HR), run_facts(PR)
    comp = (ROOT / "demos/hr-shore-staff/human_baseline/COMPARISON.md")
    comp_txt = comp.read_text(encoding="utf-8") if comp.exists() else ""
    m_all = re.search(r"\| All cases \| (\d+/\d+)[^|]*\| (\d+/\d+)", comp_txt)
    m_p = re.search(r"McNemar p = ([\d.]+)", comp_txt)
    bench = j(ROOT / "bench" / "results.json", []) or []
    tests = sum(len(re.findall(r"^def test_", p.read_text(encoding="utf-8"), re.M)) for p in (ROOT / "tests").glob("test_*.py"))
    py_lines = sum(len(p.read_text(encoding="utf-8").splitlines()) for p in (ROOT / "forgeai").rglob("*.py"))
    web_lines = sum(len(p.read_text(encoding="utf-8").splitlines()) for p in (ROOT / "forgeai/studio/static").glob("*.*"))
    prompts = len(list((ROOT / "forgeai/prompts").glob("*.md")))
    msel = (ROOT / "docs/MODEL_SELECTION.md").read_text(encoding="utf-8") if (ROOT / "docs/MODEL_SELECTION.md").exists() else ""
    mrows = re.findall(r"^\| \**([\w.:]+)\** \| ([\w.:]+) \| (\d+) \| \**(\d+)\** \| \**(\d+)\** \| \**(\d+)\** \|", msel, re.M)
    screens = sorted((ROOT / "docs" / "screens").glob("*.png"))

    hrq = hr["req"].get("interview", [])
    notes_n = sum(1 for q in hrq if q.get("source") == "requester-notes")
    hr_gaps = [x["topic"] for x in hr["g"].get("gaps", [])]
    pr_gaps = [x["topic"] for x in pr["g"].get("gaps", [])]
    pr_toolbacked = [x["topic"] for x in pr["g"].get("tool_backed", [])]
    acc = [c for c in hr["changes"] + pr["changes"] if c.get("accepted")]
    rej = [c for c in hr["changes"] + pr["changes"] if not c.get("accepted")]
    bench_built = [b for b in bench if b.get("status") == "built"]
    bench_ok = sum(1 for b in bench if b.get("ok"))

    S = []
    add = S.append
    add("# ForgeAI")
    add("> The agent that builds agents. One paragraph and a folder of documents in; a tested, grounded agent and an honest report out, on small local models.")
    add("author: ForgeAI")
    add("accent: clay")
    add("// Generated by scripts/make_brief.py. Every number on these slides is read from a file in this repository.")
    add("// Present in ForgeAI Studio (forge ui -> The brief -> Present): ← → step · P autoplay · N notes · Esc stop.")
    add("")
    add("## The challenge")
    add("Build the machine that builds the chatbot: interview the requester, refuse what the documents cannot support, generate the agent, write its tests, judge it, repair it, and report honestly. It must work on a brief it has never seen, on a small imperfect model.")
    add("```visual")
    add(f"metrics: Pipeline stages = 9 | Extensions = 6 | Demo runs committed = 2 | Unseen briefs benchmarked = {len(bench) or 'n/a'}")
    add("```")
    add("note: The real test is a brief and folder the factory has never seen, run unattended. Everything here was built for that, not for the two demos.")
    add("")
    add("## One rule underneath everything")
    add("Small models are wrong often. So no claim a model makes is believed until code has checked it.")
    add("```visual")
    add("flow: Model claim -> Check in code -> Keep / downgrade / drop -> Recorded in the run")
    add("active: Check in code")
    add("```")
    add("> Quotes must exist word for word. Numbers must match exactly. Labels are checked against the documents. The judge is tested on answers whose verdict is known. Patches must prove they helped.")
    add("")
    add("## The factory")
    add("Nine stages, each writing its artifact as it finishes, so a run can be inspected, resumed and replayed.")
    add("```visual")
    add("flow: Brief + docs -> Interview -> Groundability guard -> Agent -> Tests -> Judge -> Optimizer -> Report")
    add("active: Groundability guard")
    add("```")
    add(f"note: {prompts} prompt files, all committed and hashed into each run's manifest. {py_lines:,} lines of Python, {web_lines:,} lines of hand-written Studio front end.")
    add("")
    add("## It asks before it builds")
    add("At most five questions, only the ones that would change the agent, each with a stated default so an unattended run still proceeds. Every answer's source is recorded.")
    add("```visual")
    add(f"metrics: Questions asked (HR) = {len(hrq)} | Answered from requester notes = {notes_n} | Defaults recorded as assumptions = {len(hrq) - notes_n} | Must-answer topics = {len(hr['req'].get('must_answer', []))}")
    add("```")
    add("note: Requester notes are only used when the answer quotes them verbatim, so the stand-in cannot invent preferences.")
    add("")
    add("## It refuses to build on sand")
    add(f"The HR brief asked for **{' and '.join(hr_gaps) or 'nothing unsupported'}**. The documents say nothing about {'them' if len(hr_gaps) > 1 else 'it'}. The guard flags this before anything is generated, and the agent is told to decline instead of inventing.")
    add("```visual")
    add(f"metrics: Coverage = {pct(hr['g'].get('coverage'))} | Supported topics = {len(hr['g'].get('supported', []))} | Gaps flagged = {len(hr_gaps)} | Model verdicts overridden by code = {hr['g'].get('disagreements', 0)}")
    add("```")
    add("> A 'supported' verdict counts only if its evidence quote exists verbatim in the documents. Below 25% coverage the factory stops and builds nothing.")
    add("")
    add("## Tools have to earn their place")
    vet = "; ".join(f"{t['tool']} ({t['final_reason'][:70]})" for t in hr["vetoed"][:2])
    add(f"HR agent: **{', '.join(hr['attached']) or 'no tools'}**. The model proposed {len(hr['vetoed'])} tool(s) and code vetoed them: {vet or 'none'}.")
    add(f"Procurement agent: **{', '.join(pr['attached'])}**. Topics needing live data ({', '.join(pr_toolbacked) or 'none'}) are tool-backed, not gaps; {', '.join(pr_gaps) or 'nothing'} is a gap.")
    add("```visual")
    add("flow: Model proposes -> Precondition holds? -> Need evidenced in a supported topic? -> Not serving a gap? -> Attached")
    add("active: Need evidenced in a supported topic?")
    add("```")
    add("note: After evaluation, any tool the agent never used is removed if removing it costs no dev case.")
    add("")
    add("## It writes its own exam, and distrusts it")
    add("Answerable, cross-document, rule-application, re-phrased, tool, out-of-scope and gap questions, generated from the documents. Code then drops the weak ones before anything is scored.")
    add("```visual")
    add(f"metrics: Cases kept (HR) = {hr['st'].get('total', 'n/a')} | Dropped by self-checks = {hr['dropped']} | Answerable without the documents = {hr['leak']} | Holdout never seen by the optimizer = {hr['st'].get('holdout', 'n/a')}")
    add("```")
    add("- Facts must be verbatim spans of the source; paraphrases are repaired to the exact span or dropped")
    add("- Rule-application tests record the tempting wrong value as a trap (the hotel in Pune, which is not a metro city)")
    add("- 'Must refuse' labels are checked against the corpus; edge cases never cross the dev/holdout split")
    add("")
    add("## A judge that is judged")
    add("Code judges first: facts, numbers, refusals, citations. The model judge sees one fact at a time, and its quote must exist in the answer. Then the judge is audited on canaries whose verdict is known.")
    add("```visual")
    add(f"metrics: Canary accuracy = {pct(hr['can'].get('overall'))} | Fact verdicts decided by code = {pct(hr['code_share'])} | Verbosity effect = {('+' if (hr['can'].get('verbosity_effect') or 0) >= 0 else '')}{round(100 * (hr['can'].get('verbosity_effect') or 0))} pts | Position bias = none by design")
    add("```")
    add("note: The judge (gemma3) is a different family from the agent (qwen3). Swapping judge families changed no score: docs/MODEL_SELECTION.md.")
    add("")
    add("## Diagnose. Patch one thing. Prove it.")
    add("Failures are classified by measurement: retrieval miss, hallucination, wrong refusal, prompt defect. Each targeted patch is gated on its cases plus a regression sample; an iteration survives only if dev strictly improves.")
    add("```visual")
    add("flow: Measure the failure -> One targeted patch -> Gate: fixes targets, breaks nothing -> Keep or revert")
    add("active: Gate: fixes targets, breaks nothing")
    add("```")
    for c in acc[:2]:
        add(f"- Kept: {c['id']} `{c['target']}`, fixed {len(c['gate'].get('fixed', []))}, broke {len(c['gate'].get('broke', []))}")
    if rej:
        ex = next((c for c in rej if c["target"].startswith("section:")), rej[0])["change_summary"]
        ex = ex if len(ex) <= 120 else ex[:120].rsplit(" ", 1)[0] + "…"
        add(f"- Rejected: {len(rej)} patch(es) that did not fix their targets, e.g. \"{ex}\"")
    add("")
    add("## Results")
    hrh, prh = hr["rep"].get("holdout"), pr["rep"].get("holdout")
    add(f"Holdout first, with its 95% interval. HR {ci(hrh)}; procurement {ci(prh)}. The report then states exactly what still fails and why.")
    add("```visual")
    add(f"metrics: HR holdout = {frac(hrh)} | HR dev = {frac(hr['rep'].get('dev'))} | Procurement holdout = {frac(prh)} | Procurement dev = {frac(pr['rep'].get('dev'))}")
    add("```")
    add(f"note: HR run {hr['minutes']} min, procurement run {pr['minutes']} min, on one laptop with local models.")
    add("")
    if m_all:
        add("## Factory vs a careful human")
        add("Same brief, documents, model, runtime and judge. Only the author of the agent definition differs.")
        add("```visual")
        add(f"metrics: Factory (one paragraph) = {m_all.group(1)} | Hand-written by the developer = {m_all.group(2)} | Paired test p-value = {m_p.group(1) if m_p else 'n/a'}")
        add("```")
        add("> From one paragraph and zero human effort, the factory's agent matched or beat a hand-tuned one on the same tests - and the factory also flagged the gaps, wrote and verified the tests, and audited its own judge. The paired difference is not statistically significant, and the report says so.")
        add("")
    if bench:
        add("## Briefs it had never seen")
        add("Built for briefs it has never seen: different domains and formats, plus one adversarial brief whose documents are unrelated.")
        add("```visual")
        hb = [b for b in bench_built if b.get("holdout")]
        mean_h = sum(b["holdout"]["rate"] for b in hb) / len(hb) if hb else None
        add(f"metrics: Benchmark briefs = {len(bench)} | Correct outcome (build or stop) = {bench_ok} of {len(bench)} | Mean holdout of built agents = {pct(mean_h)} | Adversarial brief = {'stopped at the guard' if any(b.get('status', '').startswith('stopped') for b in bench) else 'n/a'}")
        add("```")
        for b in bench:
            if b.get("status") == "built":
                add(f"- {b['name']}: holdout {frac(b['holdout'])}; tools {', '.join(b['tools']) or 'none'}; gaps {len(b.get('gaps', []))}")
            else:
                add(f"- {b['name']}: {b.get('status')}")
        add("")
    if mrows:
        add("## Models chosen by measurement")
        add("One frozen eval set, re-run with different agents and judges. The best agent became the default.")
        add("```visual")
        add("metrics: " + " | ".join(f"{a} judged by {jdg} = {tot}/32" for a, jdg, d, h, tot, hal in mrows[:4]))
        add("```")
        add("note: Every profile keeps exactly three models resident, which fits Ollama's defaults on Windows with no configuration.")
        add("")
    title = {"overview": "ForgeAI Studio: the run at a glance", "groundability": "Every verdict, with its verified evidence",
             "optimizer": "Every patch, its diff, and the gate's verdict", "cases": "Every test, down to the passages",
             "explain": "How it works, told by the product itself"}
    for p in [p for p in screens if any(k in p.stem for k in title)]:
        key = next(k for k in title if k in p.stem)
        add(f"## {title.get(key, p.stem)}")
        add("```visual")
        add(f"image: docs/screens/{p.name}")
        add("caption: forge ui · standard library only · every value read from the run's artifacts")
        add("```")
        add("")
    add("## Built to run anywhere")
    add("```visual")
    add("timeline: forge doctor | forge build | forge chat | forge eval | forge regress | forge replay | forge ui")
    add("at: 7")
    add("```")
    add(f"- Windows, macOS, Linux; Python 3.10+; two dependencies; {tests} tests including an offline end-to-end run")
    add("- Soft time budget, resumable runs, and a replay of any committed run with no model installed")
    add("")
    add("## In one sentence")
    add("```visual")
    add("quote: Never believe a small model until code has checked it. That is how a factory made of imperfect parts ships an agent you can trust.")
    add("```")
    out = ROOT / "docs" / "FORGEAI.brief"
    out.write_text("\n".join(S) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({sum(1 for x in S if x.startswith('## '))} slides)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
